import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { ROOT, PUBLIC_KEY_PATH } from '../lib/config.mjs';

const origin = 'https://tesla.dangerously-skipped-permissions.com';
const request = (path, options = {}) => fetch(origin + path, { ...options, redirect: 'manual', signal: AbortSignal.timeout(20_000) });
const homepage = await request('/');
assert.equal(homepage.status, 200);
const html = await homepage.text();
assert.match(html, /Tesla Garage/);
assert.doesNotMatch(html, /static\.cloudflareinsights\.com/);
const info = await (await request('/api/session')).json();
assert.equal(info.credentialsConfigured, true);
assert.equal(info.runtime, 'cloudflare');
assert.equal(info.callbackUrl, origin + '/auth/callback');
const key = await request(PUBLIC_KEY_PATH);
assert.equal(key.status, 200);
assert.equal((await key.text()).trim(), (await readFile(join(ROOT, 'public', PUBLIC_KEY_PATH), 'utf8')).trim());
const checks = await Promise.all(['/.env', '/data/private-key.pem', '/cloudflare/worker.mjs'].map(async (path) => (await request(path)).status));
assert.deepEqual(checks, [404, 404, 404]);
assert.equal((await request('/api/vehicles')).status, 401);
assert.equal((await request('/api/logout', { method: 'POST', headers: { Origin: 'https://untrusted.example' } })).status, 403);
const start = await request('/auth/login');
assert.equal(start.status, 303);
const login = new URL(start.headers.get('location'));
assert.equal(login.origin, 'https://auth.tesla.com');
assert.equal(login.searchParams.get('redirect_uri'), origin + '/auth/callback');
const cookie = start.headers.get('set-cookie');
assert.match(cookie, /HttpOnly; Secure; SameSite=Lax/);
const invalid = await request('/auth/callback?state=invalid&code=invalid', { headers: { Cookie: cookie.split(';')[0] } });
assert.equal(invalid.headers.get('location'), '/?error=state');
assert.equal((await request('/api/logout', { method: 'POST', headers: { Origin: origin, Cookie: cookie.split(';')[0] } })).status, 200);
console.log('Live checks passed: HTTPS, configured secrets, callback URL, public key, private-file isolation, secure OAuth session creation, invalid callback rejection, and logout.');
